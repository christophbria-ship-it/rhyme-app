"""Write worker/src/lex.js from data/index.pkl.

A missing word uses the worker's default (noun, rare, not an adjective), so the
file only lists exceptions: adjectives, non-nouns, and words with zipf >= 3.8.
Flags: 1 = noun, 2 = rare (zipf < 3.8), 4 = adjective. Same cutoff as engine.bad_ending.
"""
import os, pickle
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
info = pickle.load(open(os.path.join(ROOT, "data", "index.pkl"), "rb"))["info"]
RARE = 3.8
rows = []
for w, i in info.items():
    if not i["pos"] or i["freq"] < 2.5 or " " in w or "`" in w or "${" in w:
        continue
    noun = "n" in i["pos"]
    rare = i["freq"] < RARE
    adj = "adj" in i["pos"]
    if adj or not noun or not rare:
        rows.append((w, (1 if noun else 0) | (2 if rare else 0) | (4 if adj else 0)))
rows.sort()
body = "\n".join(f"{w} {flags}" for w, flags in rows)
out = os.path.join(ROOT, "worker", "src", "lex.js")
open(out, "w").write(
    "// Generated by tools/build_worker_lex.py. Do not edit by hand.\n"
    "// Flags: 1 = noun, 2 = rare (zipf < 3.8), 4 = adjective.\n"
    "// A word that is not listed is a rare noun and not an adjective.\n"
    "export const LEX = new Map(`" + body + "`.split(\"\\n\").map(line => {\n"
    "  const sp = line.lastIndexOf(\" \");\n"
    "  return [line.slice(0, sp), Number(line.slice(sp + 1))];\n"
    "}));\n"
)
print(f"wrote {len(rows)} exceptions, {os.path.getsize(out)} bytes")
